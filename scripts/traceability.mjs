#!/usr/bin/env node
// Builds docs/traceability.md: every requirement ID in docs/spec mapped to the tests whose
// titles reference it (NFR-50, NFR-20). `--check` fails when the file is out of date, so CI
// keeps the matrix honest. Usage: node scripts/traceability.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUTPUT = join(ROOT, 'docs/traceability.md');
const ID = /\b(?:UI-AUTH|USR|SES|AUTH|DASH|THEME|ERR|HLT|API|DATA|NFR)-\d{2}\b/g;

function walk(dir, accept) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return ['node_modules', 'dist', 'coverage'].includes(entry.name) ? [] : walk(path, accept);
    }
    return accept(path) ? [path] : [];
  });
}

/** Requirement IDs in spec order, with the document that defines them. */
function specIds() {
  const ids = new Map();
  for (const file of readdirSync(join(ROOT, 'docs/spec')).sort()) {
    if (!/^\d\d-.*\.md$/.test(file)) continue;
    const text = readFileSync(join(ROOT, 'docs/spec', file), 'utf8');
    for (const [, id] of text.matchAll(/\*\*([A-Z][A-Z-]*-\d{2})\*\*/g)) {
      if (!ids.has(id)) ids.set(id, file);
    }
  }
  return ids;
}

function levelOf(file) {
  const path = relative(ROOT, file);
  if (path.startsWith('e2e/')) return 'e2e';
  if (path.startsWith('apps/web/')) return 'component';
  if (path.startsWith('apps/api/test/') || path.startsWith('apps/api/src/db/')) {
    return 'integration';
  }
  return 'unit';
}

/** Test titles (first string argument of it/test) and the IDs they mention. */
function testReferences() {
  const files = walk(ROOT, (path) => /\.(test|spec)\.tsx?$/.test(path));
  const references = [];
  const title = /\b(?:it|test)(?:\.todo)?\(\s*(['"`])((?:(?!\1).)+)\1/g;
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    for (const [, , name] of text.matchAll(title)) {
      for (const [id] of name.matchAll(ID)) {
        references.push({ id, level: levelOf(file), file: relative(ROOT, file), name });
      }
    }
  }
  return references;
}

const LEVELS = ['unit', 'integration', 'component', 'e2e'];

/** Requirements verified by the pipeline or configuration rather than a test title. */
const VERIFIED_ELSEWHERE = {
  'ERR-13': 'close-with-grace handlers in apps/api/src/main.ts (code review)',
  'NFR-01': 'package.json engines; CI runs the tests on Node 22 and 24',
  'NFR-02': 'CI starts the whole Compose stack and runs e2e against it',
  'NFR-16': 'CI step "Containers run as non-root users"; read-only root filesystems in Compose',
  'NFR-20': 'this matrix, checked for staleness in CI',
  'NFR-33': 'Delivery and Release workflows with GitHub environments',
  'NFR-50': 'CI runs unit, integration, component and e2e tests on every pull request',
  'NFR-51': 'coverage thresholds in the Vitest configs, enforced in CI',
  'NFR-52': 'required status checks in the main branch ruleset',
};

function render() {
  const ids = specIds();
  const refs = testReferences();
  const byId = new Map([...ids.keys()].map((id) => [id, []]));
  for (const ref of refs) byId.get(ref.id)?.push(ref);

  const untested = [...byId].filter(([, list]) => list.length === 0).map(([id]) => id);
  const lines = [
    '# Traceability matrix',
    '',
    '<!-- Generated by `npm run traceability`; do not edit by hand. CI fails if it is stale. -->',
    '',
    'Every requirement ID in [docs/spec](spec/README.md) and the number of tests per level whose',
    'titles reference it. Levels: unit (pure functions, schemas), integration (API against',
    'PostgreSQL), component (React with a mocked API), e2e (Playwright against the running stack).',
    '',
    `Requirements: ${ids.size}. With at least one test: ${ids.size - untested.length}.`,
    '',
  ];
  let currentDoc = '';
  for (const [id, doc] of ids) {
    if (doc !== currentDoc) {
      currentDoc = doc;
      lines.push(`## [${doc.replace(/\.md$/, '')}](spec/${doc})`, '');
      lines.push(
        '| ID | Unit | Integration | Component | E2E |',
        '| --- | --- | --- | --- | --- |',
      );
    }
    const list = byId.get(id) ?? [];
    const counts = LEVELS.map((level) => {
      const n = list.filter((ref) => ref.level === level).length;
      return n === 0 ? '' : String(n);
    });
    lines.push(`| ${id} | ${counts.join(' | ')} |`);
    const next = [...ids.keys()][[...ids.keys()].indexOf(id) + 1];
    if (!next || ids.get(next) !== doc) lines.push('');
  }
  lines.push('## Verified outside test titles', '');
  if (untested.length === 0) {
    lines.push('None.');
  } else {
    lines.push('| ID | Where |', '| --- | --- |');
    for (const id of untested) {
      lines.push(`| ${id} | ${VERIFIED_ELSEWHERE[id] ?? '**not verified yet**'} |`);
    }
  }
  lines.push('');
  return { text: lines.join('\n'), untested };
}

const { text, untested } = render();
if (process.argv.includes('--check')) {
  const current = readFileSync(OUTPUT, 'utf8');
  if (current !== text) {
    process.stderr.write('docs/traceability.md is out of date. Run `npm run traceability`.\n');
    process.exit(1);
  }
  process.stdout.write('docs/traceability.md is up to date.\n');
} else {
  writeFileSync(OUTPUT, text);
  process.stdout.write(
    `Wrote docs/traceability.md (${untested.length} requirements without tests).\n`,
  );
}
const unverified = untested.filter((id) => !(id in VERIFIED_ELSEWHERE));
if (unverified.length > 0) {
  process.stderr.write(
    `Requirements with no test and no other verification: ${unverified.join(', ')}\n`,
  );
  process.exit(1);
}
